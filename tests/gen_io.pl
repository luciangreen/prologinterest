% Regenerates tests/io_pairs.pl from the independent specification in spec.pl.
% Usage (from the repo root):  swipl tests/gen_io.pl
:- ensure_loaded('../spec.pl').
:- ensure_loaded('inputs.pl').
:- initialization(main).

main :-
    open('tests/io_pairs.pl', write, S),
    format(S, "% 200 input/output pairs, generated by tests/gen_io.pl from spec.pl.~n", []),
    format(S, "% io(Id, Predicate, Input, ExpectedOutput).~n", []),
    format(S, ":- style_check(-singleton).~n", []),
    forall(input(Id, P, I),
           ( spec_for(P, SP), once(call(SP, I, O)),
             format(S, "~q.~n", [io(Id, P, I, O)]) )),
    close(S), halt.
